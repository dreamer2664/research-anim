"""REEL index — a hub page listing the three studies.

Generated like the reels, so the series stays consistent and nothing is
hand-maintained. Links are relative, so the folder works from file://.
"""

from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import reelkit  # noqa: E402

STUDIES = [
    ("01-easing-curves.html", "01", "Easing curves, one clock",
     "Linear / ease-in-out / cubic-bezier(.34,1.56,.64,1) over an identical "
     "1400 ms and an identical distance."),
    ("02-spring-vs-tween.html", "02", "Spring vs tween, same target",
     "A damped spring, solved exactly, against a fixed 700 ms bezier: "
     "overshoot, settling tails, and retargeting mid-flight."),
    ("03-keyframe-spacing.html", "03", "Keyframe spacing is the timing",
     "Three key sets, straight-line in-betweens, one 1800 ms move: mechanical, "
     "hand-drawn, and hitched."),
]

BODY = """
<ul class="index">
{items}
</ul>
<p class="hint" style="margin-top:22px">Each reel is a single self-contained file
&mdash; no CDN, no build step, no network. Append <code>?still=1&amp;t=0.42</code>
to any of them to freeze one frame at 42% of the cycle.</p>
""".format(items="\n".join(
    f'  <li><a href="{href}"><span class="num">{num}</span>'
    f'<span class="t">{title}</span><span class="d">{desc}</span></a></li>'
    for href, num, title, desc in STUDIES
))

EXTRA_CSS = """
.index{list-style:none;padding:0;margin:0;display:grid;gap:10px}
.index a{display:grid;grid-template-columns:52px 1fr;grid-template-rows:auto auto;
  gap:2px 14px;text-decoration:none;color:var(--ink);background:var(--panel);
  border:1px solid var(--line);border-radius:10px;padding:14px 16px}
.index a:hover{border-color:#3a4756;background:#172029}
.index .num{grid-row:1/3;font:600 22px/1 var(--mono);color:var(--faint);align-self:center}
.index .t{font-weight:640}
.index .d{color:var(--dim);font-size:13px}
""".strip()


def render() -> str:
    return reelkit.page(
        reel_id="index",
        number="index",
        title="REEL — short animation studies",
        lede="Three studies on timing: what an easing curve does to speed, what a spring does "
             "after it arrives, and what keyframe spacing does before any curve is applied. "
             "Each page is one file and every number on it is measured, not asserted.",
        body=BODY,
        script="",
        extra_css=EXTRA_CSS,
        footer_note="REEL · research-anim · generated by tools/gen_index.py",
        nav=False,
    )


if __name__ == "__main__":
    out = reelkit.REELS / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(), encoding="utf-8")
    print("wrote", out.relative_to(reelkit.ROOT))
